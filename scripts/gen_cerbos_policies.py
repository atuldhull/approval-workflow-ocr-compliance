"""Generates the Cerbos policies from backend/app/platform/policy.py, so both policy engines enforce one table.

    python scripts/gen_cerbos_policies.py           # write infra/cerbos/policies/
    python scripts/gen_cerbos_policies.py --check   # fail if the committed policies are out of date
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "backend")]

from app.platform.policy import KINDS, POLICY, REGION_SCOPED_KINDS  # noqa: E402
from contracts.enums import Role  # noqa: E402

OUT = ROOT / "infra" / "cerbos" / "policies"
HEADER = "# Generated by scripts/gen_cerbos_policies.py from backend/app/platform/policy.py - do not edit.\n"

INSTITUTION_SCOPE = ("has(P.attr.institution_id) && (has(R.attr.owner_institution_id) "
                     "? R.attr.owner_institution_id == P.attr.institution_id : R.attr.is_collection == true)")
REGION_REQUIRED = "has(P.attr.region) && has(R.attr.region) && R.attr.region == P.attr.region"
REGION_IF_STATED = "has(P.attr.region) && (!has(R.attr.region) || R.attr.region == P.attr.region)"


def condition(role: Role, kind: str) -> str | None:
    if role == Role.INSTITUTION:
        return INSTITUTION_SCOPE
    if role == Role.RO_OFFICER:
        return REGION_REQUIRED if kind in REGION_SCOPED_KINDS else REGION_IF_STATED
    return None


def policy_for(kind: str) -> dict:
    rules = []
    for role in Role:
        actions = sorted(a for a, roles in POLICY.items() if role in roles)
        if not actions:
            continue
        rule = {"name": f"{role.value.lower()}", "actions": actions, "effect": "EFFECT_ALLOW", "roles": [role.value]}
        cond = condition(role, kind)
        if cond:
            rule["condition"] = {"match": {"expr": cond}}
        rules.append(rule)
    return {"apiVersion": "api.cerbos.dev/v1",
            "resourcePolicy": {"version": "default", "resource": kind, "rules": rules}}


def render() -> dict[str, str]:
    return {f"{kind}.yaml": HEADER + yaml.safe_dump(policy_for(kind), sort_keys=False, width=200)
            for kind in sorted(KINDS)}


def main() -> int:
    files = render()
    if "--check" in sys.argv:
        stale = [n for n, body in files.items() if not (OUT / n).exists() or (OUT / n).read_text(encoding="utf-8") != body]
        extra = [p.name for p in OUT.glob("*.yaml") if p.name not in files] if OUT.exists() else []
        for n in stale + extra:
            print("ERROR", f"infra/cerbos/policies/{n} is out of date - run: python scripts/gen_cerbos_policies.py")
        print("cerbos policies ok" if not stale + extra else "cerbos policies out of date")
        return 1 if stale or extra else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p in OUT.glob("*.yaml"):
        p.unlink()
    for n, body in files.items():
        (OUT / n).write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {len(files)} policies to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
